// Registration of one AI use case (#472): validation, planning and
// execution. Nothing in this file parses flags or prints: `talon agents
// add` (agents_add.go) passes a registrationRequest and renders the result.
//
// A registration touches three stores that share no transaction: the
// evidence database, the secrets vault and the agent file. It is therefore
// NOT atomic, and it does not claim to be. What it guarantees instead:
//
//   - One at a time. Registration, and the recovery of an earlier one, run
//     under the installation's registration lock (internal/registration):
//     an advisory lock in the data directory, which every registration of
//     the installation shares whatever tenant, agents_dir or config file it
//     names. Everything is re-read under the lock. The kernel releases the
//     lock when the process exits, so a killed registration leaves none.
//   - Order. (1) a signed INTENT record that commits to the artifacts it is
//     about to create (the vault ownership token of the key version, the
//     SHA-256 of the agent file), (2) the key, created only if the vault has
//     no secret of that name, (3) the agent file, created only if no file of
//     that name exists, (4) the fleet re-scan, (5) the signed COMPLETION
//     record. The key is printed only after (5).
//   - No overwrite. Neither an existing agent file nor an existing secret is
//     ever replaced.
//   - Owned cleanup. A registration that fails with an ordinary error
//     removes exactly what it created (its own key version, the very file
//     it published) and writes a signed ROLLED BACK record saying what it
//     removed and what it could not.
//   - No usable unintended authority. The key is generated by this command
//     and shown only on completion, so a registration that did not complete
//     leaves, at worst, a key nobody has ever seen. A running server may
//     load the use case between step 3 and a rollback; it drops it at its
//     next reload, and nobody can present its key in between.
//   - Recovery by proof, never by guess. A process that dies after step 1
//     leaves an intent without a terminal record. Under the lock that intent
//     cannot belong to a running registration. The next registration of the
//     name removes ONLY artifacts the signed intent proves that registration
//     created (same ownership token, same file digest), records it as rolled
//     back, and leaves anything else untouched and named. An intent alone is
//     never a reason to delete something.

// registrationRequest is what the operator asked for.
type registrationRequest struct {
	Name, Tenant, Description, Owner string
	// Marker is the registration marker of the run that will write the
	// file; empty for a plan that only inspects.
	Marker string
	// AllowNoCompanyPolicy permits a registration when no gateway config
	// (and so no organization policy) exists.
	AllowNoCompanyPolicy bool
}

var agentNameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,62}$`)

const agentsAddTemplate = `# AI use case {{ printf "%q" .Name }} — registered with 'talon agents add'.
` + registrationMarkerPrefix + `{{ if .Marker }}{{ .Marker }}{{ else }}(assigned when the use case is registered){{ end }}
#   (not a secret and not configuration: it identifies the registration that
#   wrote this file, so that an interrupted registration is cleaned up only
#   when the file is its own)
# Every policy not set here is the company's organization policy
# (talon.config.yaml gateway.organization_policy): budgets, PII handling,
# models, tools, forbidden actions, approval rules and amount limits.
# Add a block below only to tighten it for this use case; company
# constraints and denials cannot be lifted from this file.
agent:
  name: {{ printf "%q" .Name }}
  description: {{ printf "%q" .Description }}
  version: 1.0.0
  tenant_id: {{ printf "%q" .Tenant }}
  # The Talon key this use case presents (vault secret NAME, never the value).
  key:
    secret_name: {{ printf "%q" .SecretName }}
{{- if or .Purpose .Owner }}
  # What this use case is for and who operates it. Shown by 'talon agents'
  # and the Operations Console; attribution for people, not authentication.
  use_case:
{{- if .Purpose }}
    purpose: {{ printf "%q" .Purpose }}
{{- end }}
{{- if .Owner }}
    owners:
      technical: {{ printf "%q" .Owner }}
{{- end }}
{{- end }}

policies:
  cost_limits: {}   # inherit organization_policy.defaults daily_cost / monthly_cost
`

// registrationMarkerPrefix starts the comment line of a generated agent file
// that carries the registration marker.
const registrationMarkerPrefix = "# registration: "

// newRegistrationMarker returns a random marker for one registration. The
// generated file is otherwise identical for every registration of the same
// name, owner and tenant; the marker makes this registration's file, and so
// the digest its signed intent commits to, its own.
func newRegistrationMarker() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("generating a registration marker: %w", err)
	}
	return hex.EncodeToString(b), nil
}

type agentsAddPlan struct {
	Name, Tenant, Description, Owner, SecretName string
	// Purpose is the description the operator gave ("" when none was given;
	// Description then holds a generated default that is not written as the
	// use case's purpose).
	Purpose   string
	Dir, Path string
	Content   []byte
	// Marker is the registration marker written into Content ("" in a plan
	// that only inspects: a dry run, or the plan made before the lock).
	Marker string
	// AgentsDirMissing: agents_dir does not exist yet; a real registration
	// creates it, a dry run does not.
	AgentsDirMissing bool
	// CompanyPolicy states what the gateway config declares and whether a
	// running gateway loaded it.
	CompanyPolicy string
	// NoOrganizationPolicy: no gateway config was found, so nothing is
	// inherited and the new use case has no budget cap of its own.
	NoOrganizationPolicy bool
	// AbsPath is Path as an absolute path: what a signed record names.
	AbsPath string
	// FileSHA256 is the digest of Content: the intent commits to it.
	FileSHA256 string
	// Unresolved are earlier registrations of this name whose intent has no
	// terminal record, as read WITHOUT the lock: whether one of them is
	// still running is not known here. The execution resolves them under
	// the lock. UnresolvedIncomplete: there are more than one lookup reads.
	Unresolved           []registration.Unresolved
	UnresolvedIncomplete bool
}

// registrationResult is what a completed registration produced.
type registrationResult struct {
	// Key is the generated Talon key. It exists in memory only between the
	// completion record and the moment it is shown.
	Key        string
	IntentID   string
	EvidenceID string
	// Recovered says, per earlier interrupted registration of this name,
	// what was done about it (each is now recorded as rolled back).
	Recovered []string
	// Residual names what this registration could not clean up although it
	// completed (a temporary file). It is also in the completion record.
	Residual []string
}

// Steps of a registration, in order.
const (
	stepIntentRecorded = "intent_recorded"
	stepKeyStored      = "key_stored"
	stepFilePublished  = "file_published"
	stepFleetValidated = "fleet_validated"
	stepCompleted      = "completed"
	// stepRollbackRecord is the signed rollback record of a failed
	// registration (a fault point only: it is not a step of a successful one).
	stepRollbackRecord = "rollback_record"
	// pointPlanRead is not a step: it is the moment in planning after the
	// unfinished registrations of the name were read.
	pointPlanRead = "plan_read"
)

// registrationFault is the fault-injection seam of a registration. It is a
// no-op in the product; tests replace it to fail or to kill the process at
// an exact point. It is called at two kinds of point:
//
//	"fail:<step>"  before the step: a returned error is the step's OWN
//	               failure (the vault write failed, the record could not be
//	               written), and the step is not performed;
//	"<step>"       after the step succeeded: a returned error is a failure
//	               between this step and the next.
var registrationFault = func(point string) error { return nil }

// faultOr performs do unless the step's own failure is injected.
func faultOr(step string, do func() error) error {
	if err := registrationFault("fail:" + step); err != nil {
		return err
	}
	return do()
}

// planRegistration validates everything that needs no write: the
// installation mode, the existing fleet, the name, earlier unfinished
// registrations of the name, the company policy and the rendered file. It
// creates nothing, on a fresh installation too.
//
// judgeName decides whether a name that looks taken (an agent file or a
// vault secret exists) is refused. That judgment is only sound under the
// registration lock: without it, the key or the file may belong to a
// registration that is running right now and has not finished. The
// execution plans with judgeName under the lock; the plan made before the
// lock does not judge.
func planRegistration(ctx context.Context, cfg *config.Config, req registrationRequest, judgeName bool) (*agentsAddPlan, error) {
	name := req.Name
	if !agentNameRe.MatchString(name) {
		return nil, fmt.Errorf("invalid use case name %q: lower-case letters, digits, '-' and '_', starting with a letter or digit, at most 63 characters", name)
	}
	if strings.TrimSpace(cfg.AgentsDir) == "" {
		return nil, errors.New("agents_dir is not configured: 'talon agents add' registers use cases in an agents_dir fleet. Set agents_dir in talon.config.yaml (or TALON_AGENTS_DIR), move an existing agent.talon.yaml to <agents_dir>/<name>/agent.talon.yaml, then retry")
	}
	tenant := strings.TrimSpace(req.Tenant)
	if tenant == "" {
		tenant = "default"
	}
	desc := strings.TrimSpace(req.Description)
	if desc == "" {
		desc = "AI use case " + name
	}
	plan := &agentsAddPlan{
		Name: name, Tenant: tenant, Description: desc, Purpose: strings.TrimSpace(req.Description), Owner: strings.TrimSpace(req.Owner), SecretName: name + "-talon-key",
		Dir: filepath.Join(cfg.AgentsDir, name), Marker: req.Marker,
	}
	plan.Path = filepath.Join(plan.Dir, agentcatalog.AgentConfigFilename)
	plan.AbsPath = plan.Path
	if abs, err := filepath.Abs(plan.Path); err == nil {
		plan.AbsPath = abs
	}

	if err := checkNameAvailable(ctx, cfg, plan, judgeName); err != nil {
		return nil, err
	}
	cp, err := readCompanyPolicy(cfg)
	if err != nil {
		return nil, err
	}
	plan.CompanyPolicy, plan.NoOrganizationPolicy = cp.String(), cp.State != companyPolicyConfigured
	if cp.State != companyPolicyConfigured && !req.AllowNoCompanyPolicy {
		return nil, fmt.Errorf("%s.\nA use case registered now would run without the company's budget, PII and tool rules, so nothing was written.\n  Fix:  add a gateway.organization_policy block to the gateway config (starter: examples/pilot/talon.config.yaml), then run the command again.\n  Or:   register without a company policy on purpose with --no-company-policy", cp.Configured)
	}
	var b strings.Builder
	if err := template.Must(template.New("agent").Parse(agentsAddTemplate)).Execute(&b, plan); err != nil {
		return nil, err
	}
	plan.Content = []byte(b.String())
	sum := sha256.Sum256(plan.Content)
	plan.FileSHA256 = hex.EncodeToString(sum[:])
	if err := validateAgentContent(ctx, plan.Content); err != nil {
		return nil, fmt.Errorf("the generated agent file does not validate (nothing was written): %w", err)
	}
	return plan, nil
}

// checkNameAvailable reads what exists under the name and refuses a name
// that is taken: by a registered use case, an agent file or a vault secret.
// It reads only.
//
// Earlier registrations of the name without a terminal record are noted on
// the plan and are NOT judged here: without the registration lock it is not
// known whether one of them is running right now. While such an intent
// exists the artifacts under the name may be its leftovers, so the name is
// not refused yet; the execution decides under the lock (resolveUnresolved)
// and then applies the same refusals.
func checkNameAvailable(ctx context.Context, cfg *config.Config, plan *agentsAddPlan, judgeName bool) error {
	lookup, err := unresolvedRegistrations(ctx, cfg, plan.Name)
	if err != nil {
		return err
	}
	plan.Unresolved, plan.UnresolvedIncomplete = lookup.Unresolved, !lookup.Complete
	// Between this read and the checks below another registration can write
	// its intent and its key. That gap is why the name is judged under the
	// lock only (judgeName); the fault point lets a test hold a plan in it.
	if err := registrationFault(pointPlanRead); err != nil {
		return err
	}
	if _, err := os.Stat(cfg.AgentsDir); os.IsNotExist(err) {
		plan.AgentsDirMissing = true // a first registration: no fleet to validate yet
	} else if _, err := agentcatalog.DiscoverAgents(ctx, cfg.AgentsDir); err != nil {
		return fmt.Errorf("the existing fleet under %s does not validate, so nothing was added (fix it first; 'talon validate --dir %s'): %w", cfg.AgentsDir, cfg.AgentsDir, err)
	}
	if len(plan.Unresolved) > 0 || !judgeName {
		return nil
	}
	return nameOccupied(ctx, cfg, plan)
}

// nameOccupied refuses a name that is in use, whoever uses it.
func nameOccupied(ctx context.Context, cfg *config.Config, plan *agentsAddPlan) error {
	if _, err := os.Stat(cfg.AgentsDir); err == nil {
		scan, err := agentcatalog.DiscoverAgents(ctx, cfg.AgentsDir)
		if err != nil {
			return fmt.Errorf("the existing fleet under %s does not validate, so nothing was added (fix it first; 'talon validate --dir %s'): %w", cfg.AgentsDir, cfg.AgentsDir, err)
		}
		for i := range scan.Agents {
			if scan.Agents[i].Name == plan.Name {
				return fmt.Errorf("use case %q is already registered (%s)", plan.Name, scan.Agents[i].Path)
			}
		}
	}
	if _, err := os.Stat(plan.Path); err == nil {
		return fmt.Errorf("%s already exists", plan.Path)
	}
	keyExists, err := vaultSecretExists(ctx, cfg, plan.SecretName)
	if err != nil {
		return err
	}
	if keyExists {
		return existingKeyError(plan)
	}
	return nil
}

// vaultSecretExists reads the vault read-only: planning never initializes
// or writes a vault, and reports a secret of the name as taken whoever
// stored it.
func vaultSecretExists(ctx context.Context, cfg *config.Config, name string) (bool, error) {
	if _, err := os.Stat(cfg.SecretsDBPath()); err != nil {
		return false, nil //nolint:nilerr // no vault yet: nothing is stored
	}
	_, err := secrets.MetadataReadOnly(ctx, cfg.SecretsDBPath(), name)
	switch {
	case err == nil:
		return true, nil
	case errors.Is(err, secrets.ErrSecretNotFound):
		return false, nil
	}
	return false, fmt.Errorf("reading the secrets vault: %w", err)
}

// unresolvedRegistrations reads the evidence store read-only (it creates
// none) for registrations of name whose intent has no terminal record.
func unresolvedRegistrations(ctx context.Context, cfg *config.Config, name string) (registration.Lookup, error) {
	if _, err := os.Stat(cfg.EvidenceDBPath()); err != nil {
		return registration.Lookup{Complete: true}, nil //nolint:nilerr // no evidence store yet: nothing was ever registered
	}
	ro, err := evidence.OpenReadOnly(cfg.EvidenceDBPath(), cfg.SigningKey)
	if err != nil {
		if strings.Contains(strings.ToLower(err.Error()), "no such table") {
			// The file exists and has no evidence table: a store another
			// registration is creating right now (a plan made before the
			// lock can see that moment), or one whose creation was cut off.
			// No record was ever written through it. The vault read treats
			// a vault without its table the same way.
			return registration.Lookup{Complete: true}, nil
		}
		return registration.Lookup{}, fmt.Errorf("reading the evidence store: %w", err)
	}
	defer ro.Close()
	out, err := registration.FindUnresolved(ctx, ro, name)
	if err != nil {
		return registration.Lookup{}, fmt.Errorf("reading registration records: %w", err)
	}
	return out, nil
}

func existingKeyError(plan *agentsAddPlan) error {
	return fmt.Errorf("vault secret %q already exists (a key that may be in use); refusing to overwrite it, and nothing was written. A use case gets a key that 'talon agents add' generates: remove the existing secret deliberately with 'talon secrets delete %s' if it is not in use, or choose another name", plan.SecretName, plan.SecretName)
}

// registrationLockWait is how long a registration waits for another
// registration of the installation to finish. A variable for tests.
var registrationLockWait = 30 * time.Second

// registrationLockSupported is registration.LockSupported; a variable so a
// test can prove on any platform that a registration is refused without it.
var registrationLockSupported = registration.LockSupported

// executeRegistration performs a registration (see the file comment for
// order and guarantees). It takes the registration lock, plans AGAIN under
// it (what was read before the lock may be stale), resolves earlier
// registrations of the name that never finished, and only then writes. It
// returns the plan it executed.
func executeRegistration(ctx context.Context, cfg *config.Config, req registrationRequest) (*agentsAddPlan, *registrationResult, error) {
	release, err := acquireRegistrationLock(ctx, cfg)
	if err != nil {
		return nil, nil, err
	}
	defer release()

	// This run's marker goes into the file it generates and into its signed
	// intent: the file it publishes is then recognizably its own.
	if req.Marker, err = newRegistrationMarker(); err != nil {
		return nil, nil, err
	}
	plan, err := planRegistration(ctx, cfg, req, true)
	if err != nil {
		return nil, nil, err
	}
	run, closeStores, err := openRegistrationRun(ctx, cfg, plan)
	if err != nil {
		return nil, nil, err
	}
	defer closeStores()
	res := &registrationResult{}
	if res.Recovered, err = run.resolveUnresolved(); err != nil {
		return nil, nil, err
	}
	if len(plan.Unresolved) > 0 {
		// The earlier registrations are resolved; the name is now judged
		// like any other.
		if err := nameOccupied(ctx, cfg, plan); err != nil {
			return nil, nil, err
		}
	}

	if err := run.perform(ctx, cfg, res); err != nil {
		return nil, nil, err
	}
	return plan, res, nil
}

// acquireRegistrationLock takes the installation's registration lock. The
// lock file lives in the data directory; a first registration creates that
// directory, as it creates the stores in it.
func acquireRegistrationLock(ctx context.Context, cfg *config.Config) (release func(), err error) {
	// Fail closed where the lock does not exist: without it two
	// registrations are not serialized and a running registration cannot be
	// told from an interrupted one. Nothing is created first.
	if !registrationLockSupported {
		return nil, fmt.Errorf("%w: 'talon agents add' needs it to keep two registrations of one installation apart, so it does not run here and nothing was written. Register the use case from a Linux or macOS host that has this installation's data directory (--dry-run works on this platform)", registration.ErrLockUnsupported)
	}
	if err := cfg.EnsureDataDir(); err != nil {
		return nil, fmt.Errorf("creating the data directory %s: %w", cfg.DataDir, err)
	}
	release, err = registration.Acquire(ctx, cfg.DataDir, registrationLockWait)
	if errors.Is(err, registration.ErrLockBusy) {
		return nil, fmt.Errorf("%w. Nothing was written and nothing of the running registration was touched: an intent it has written is in progress, not interrupted. Retry when it has finished", err)
	}
	if err != nil {
		return nil, err
	}
	if err := registrationFault("lock_acquired"); err != nil {
		release()
		return nil, err
	}
	return release, nil
}

// perform writes the registration: intent, key, file, fleet check,
// completion. Each step is followed by its fault point; a failure anywhere
// before the completion record undoes what the run has created so far.
func (r *registrationRun) perform(ctx context.Context, cfg *config.Config, res *registrationResult) error {
	plan := r.plan
	steps := []struct {
		name string
		do   func() error
	}{
		{stepIntentRecorded, func() (err error) {
			res.IntentID, err = r.record(registration.TypeIntent, r.commitments().Reasons()...)
			return err
		}},
		{stepKeyStored, r.storeKey},
		{stepFilePublished, r.publishFile},
		{stepFleetValidated, func() error {
			if err := verifyFleetAfterAddFn(ctx, cfg, plan); err != nil {
				return fmt.Errorf("the fleet does not validate with the new use case: %w", err)
			}
			return nil
		}},
	}
	for i, st := range steps {
		if err := faultOr(st.name, st.do); err != nil {
			if i == 0 {
				return fmt.Errorf("recording the registration intent as signed evidence (nothing else was written): %w", err)
			}
			return r.undo(err)
		}
		if err := registrationFault(st.name); err != nil {
			return r.undo(err)
		}
	}
	err := faultOr(stepCompleted, func() (err error) {
		notes := []string{"key: generated and stored as vault secret " + plan.SecretName + " (the value is never recorded)", "intent: " + res.IntentID}
		for _, left := range r.residual {
			notes = append(notes, "residual: "+left)
		}
		res.EvidenceID, err = r.record(registration.TypeRegistered, notes...)
		return err
	})
	if err != nil {
		return r.undo(fmt.Errorf("recording the registration as signed evidence: %w", err))
	}
	if err := registrationFault(stepCompleted); err != nil {
		// The registration is complete and recorded; only showing the key
		// failed. It is reported as such, never rolled back.
		return fmt.Errorf("the registration of %q completed (evidence %s) but its key could not be shown: %w. Replace the key with 'talon secrets set %s' (value on stdin) and restart 'talon serve'", plan.Name, res.EvidenceID, err, plan.SecretName)
	}
	res.Key, res.Residual = r.key, r.residual
	return nil
}

// openRegistrationRun creates the agents_dir when this is the installation's
// first registration, opens the evidence store and the vault, and prepares
// in memory what the intent commits to: the key and the ownership token of
// the vault version it will be stored as. Nothing of the registration is
// written yet.
func openRegistrationRun(ctx context.Context, cfg *config.Config, plan *agentsAddPlan) (*registrationRun, func(), error) {
	if plan.AgentsDirMissing {
		// The first registration of a new agents_dir installation.
		if err := os.MkdirAll(cfg.AgentsDir, 0o755); err != nil {
			return nil, nil, fmt.Errorf("creating agents_dir %s: %w", cfg.AgentsDir, err)
		}
	}
	evStore, err := evidence.NewStore(cfg.EvidenceDBPath(), cfg.SigningKey)
	if err != nil {
		return nil, nil, fmt.Errorf("opening the evidence store (nothing was written): %w", err)
	}
	store, err := secrets.NewSecretStore(cfg.SecretsDBPath(), cfg.SecretsKey)
	if err != nil {
		_ = evStore.Close()
		return nil, nil, fmt.Errorf("opening the secrets vault (nothing was written): %w", err)
	}
	closeStores := func() { _ = store.Close(); _ = evStore.Close() }
	run := &registrationRun{ctx: ctx, cfg: cfg, plan: plan, ev: evStore, vault: store, correlation: "al_" + uuid.New().String()[:12]}
	if run.key, err = newAgentKey(); err != nil {
		closeStores()
		return nil, nil, err
	}
	if run.own, err = store.NewOwnership(plan.SecretName); err != nil {
		closeStores()
		return nil, nil, fmt.Errorf("preparing the key (nothing was written): %w", err)
	}
	return run, closeStores, nil
}

// commitments are what the signed intent says this registration is about to
// create. A later process proves ownership of a leftover from them.
func (r *registrationRun) commitments() registration.Commitments {
	return registration.Commitments{
		SecretName: r.plan.SecretName, KeyOwnershipToken: r.own.Token(),
		AgentFile: r.plan.AbsPath, FileSHA256: r.plan.FileSHA256, Marker: r.plan.Marker,
	}
}

// storeKey creates the vault secret, as the version the intent committed
// to, only if none of that name exists (readable only as this use case in
// its tenant).
func (r *registrationRun) storeKey() error {
	err := r.vault.CreateOwned(r.ctx, r.own, []byte(r.key), secrets.ACL{Tenants: []string{r.plan.Tenant}, Agents: []string{r.plan.Name}})
	if errors.Is(err, secrets.ErrSecretExists) {
		// A secret stored since planning (by something that is not a
		// registration: registrations are serialized).
		return existingKeyError(r.plan)
	}
	if err != nil {
		return fmt.Errorf("storing the key in the vault: %w", err)
	}
	r.keyCreated = true
	return nil
}

// publishFile creates the agent file. Publication and the cleanup of the
// temporary file are separate facts (#567 review): once the file is linked
// it IS published and this run owns it, whatever happens to the temporary
// file afterwards.
func (r *registrationRun) publishFile() error {
	published, residual, err := publishAgentFile(r.plan)
	if published != nil {
		r.published = published
	}
	if residual != "" {
		r.residual = append(r.residual, residual)
	}
	return err
}

// registrationRun is the state of one executing registration: what it has
// created so far, which is exactly what a failure may remove.
type registrationRun struct {
	ctx         context.Context //nolint:containedctx // one short-lived command invocation
	cfg         *config.Config
	plan        *agentsAddPlan
	ev          *evidence.Store
	vault       *secrets.SecretStore
	correlation string
	// key and own exist in memory from the start: the intent commits to own
	// before the key is stored.
	key        string
	own        secrets.Ownership
	keyCreated bool
	// published identifies the very file this run linked into place (nil
	// until then). Only that file is ever removed by this run.
	published os.FileInfo
	// residual names what could not be cleaned up (a temporary file).
	residual []string
}

func (r *registrationRun) record(kind string, extra ...string) (string, error) {
	return r.recordFor(r.correlation, r.plan.Tenant, kind, extra...)
}

func (r *registrationRun) recordFor(correlation, tenant, kind string, extra ...string) (string, error) {
	id := "al_" + uuid.New().String()[:12]
	reasons := []string{"company policy: " + r.plan.CompanyPolicy}
	if kind != registration.TypeIntent {
		// The intent names the file among its commitments.
		reasons = append([]string{"config: " + r.plan.AbsPath}, reasons...)
	}
	reasons = append(reasons, extra...)
	return id, r.ev.Store(r.ctx, &evidence.Evidence{
		ID: id, CorrelationID: correlation, Timestamp: time.Now().UTC(), TenantID: tenant, AgentID: r.plan.Name,
		InvocationType: kind, RequestSourceID: operatorID(),
		PolicyDecision: evidence.PolicyDecision{Allowed: true, Action: kind, Reasons: reasons},
	})
}

// stillPublished reports whether the file now at the path is the very one
// this run published. The inode alone does not say so: a file system hands a
// freed inode number to the next file, so a file that someone removed and
// wrote again can carry the same number. The file is this run's only when
// its identity, its modification time, its size and its content are all
// what was published.
func (r *registrationRun) stillPublished(now os.FileInfo) bool {
	if !os.SameFile(now, r.published) || !now.ModTime().Equal(r.published.ModTime()) || now.Size() != r.published.Size() {
		return false
	}
	raw, err := os.ReadFile(r.plan.Path)
	if err != nil {
		return false
	}
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:]) == r.plan.FileSHA256
}

// removePublished removes the agent file only if the file at the path is
// still the very one this run published. A file another process or operator
// put there since is left alone.
func (r *registrationRun) removePublished() (did, left string) {
	now, err := os.Lstat(r.plan.Path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return "the agent file this registration published was already gone", ""
	case err != nil:
		return "", fmt.Sprintf("the agent file %s could not be inspected (%v): it was left in place", r.plan.Path, err)
	case !r.stillPublished(now):
		return "", fmt.Sprintf("the file at %s is no longer the one this registration published (it was replaced since): it was left untouched", r.plan.Path)
	}
	if err := os.Remove(r.plan.Path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Sprintf("the agent file %s could not be removed (%v): a running server will otherwise load it", r.plan.Path, err)
	}
	_ = os.Remove(r.plan.Dir) // only when empty
	return "removed the agent file this registration published", ""
}

// undo removes what THIS registration created — its own key version (never
// a secret someone else stored under the name) and the very file it
// published — records what it did as signed evidence, and reports in the
// returned error anything it could not remove: a failed registration never
// leaves an undisclosed key or file behind.
func (r *registrationRun) undo(cause error) error {
	var left, did []string
	if r.published != nil {
		d, l := r.removePublished()
		if d != "" {
			did = append(did, d)
		}
		if l != "" {
			left = append(left, l)
		}
	}
	if r.keyCreated {
		removed, err := r.vault.DeleteOwned(r.ctx, r.own)
		switch {
		case err != nil:
			left = append(left, fmt.Sprintf("the key stored as vault secret %q could not be removed (%v); it was never shown, so nobody can use it", r.plan.SecretName, err))
		case removed:
			did = append(did, "removed the key this registration stored")
		default:
			did = append(did, "the key this registration stored was already gone")
		}
	}
	left = append(left, r.residual...)
	if len(did) == 0 {
		did = append(did, "nothing had been created")
	}
	notes := []string{"cause: " + cause.Error(), "cleanup: " + strings.Join(did, "; ")}
	if len(left) > 0 {
		notes = append(notes, "NOT removed: "+strings.Join(left, "; "))
	}
	recordErr := faultOr(stepRollbackRecord, func() error {
		_, err := r.record(registration.TypeRolledBack, notes...)
		return err
	})
	unrecorded := ""
	if recordErr != nil {
		unrecorded = fmt.Sprintf("the rollback could not be recorded as evidence (%v): the signed intent has no terminal record, so 'talon doctor' and the next 'talon agents add %s' report this registration as unresolved", recordErr, r.plan.Name)
	}
	switch {
	case len(left) > 0 && unrecorded != "":
		return fmt.Errorf("%w; the registration was NOT fully undone: %s; and %s", cause, strings.Join(left, "; "), unrecorded)
	case len(left) > 0:
		return fmt.Errorf("%w; the registration was NOT fully undone: %s", cause, strings.Join(left, "; "))
	case unrecorded != "":
		return fmt.Errorf("%w; what this registration created was removed (%s), but %s", cause, strings.Join(did, "; "), unrecorded)
	}
	return fmt.Errorf("%w; nothing of this registration was left behind", cause)
}

// Company policy states of an installation's gateway config.
const (
	companyPolicyNone       = "none"       // no gateway config file
	companyPolicyUnset      = "unset"      // a gateway config without an organization_policy block
	companyPolicyConfigured = "configured" // an explicit organization_policy block
)

// companyPolicy is what a registration reports about the company policy:
// what the FILE says, and separately whether a running process has loaded
// that file. A configured policy is not called active without that proof.
type companyPolicy struct {
	State      string
	Configured string // what the gateway config declares
	Runtime    string // whether a running gateway loaded this exact file
}

func (c companyPolicy) String() string {
	return c.Configured + ". Runtime: " + c.Runtime
}

// readCompanyPolicy reads the gateway config `talon serve` loads. A present
// but invalid file is an error. A file WITHOUT an organization_policy block
// is not a company policy: the loader's built-in defaults would apply, which
// nobody chose.
func readCompanyPolicy(cfg *config.Config) (companyPolicy, error) {
	path := gatewayConfigPath("")
	raw, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return companyPolicy{State: companyPolicyNone, Configured: "no company policy: no gateway config at " + path, Runtime: "nothing to load"}, nil
	}
	if err != nil {
		return companyPolicy{}, fmt.Errorf("reading gateway config %s: %w", path, err)
	}
	gw, err := gateway.LoadGatewayConfig(path)
	if err != nil {
		return companyPolicy{}, fmt.Errorf("gateway config %s is present but invalid: %w — fix it first (serve refuses to start on this file)", path, err)
	}
	var doc struct {
		Gateway struct {
			OrganizationPolicy map[string]any `yaml:"organization_policy"`
		} `yaml:"gateway"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return companyPolicy{}, fmt.Errorf("gateway config %s: %w", path, err)
	}
	sum := sha256.Sum256(raw)
	runtime := gatewayConfigActivation(cfg, hex.EncodeToString(sum[:]))
	if len(doc.Gateway.OrganizationPolicy) == 0 {
		return companyPolicy{State: companyPolicyUnset, Configured: "no company policy: " + path + " has no gateway.organization_policy block (only built-in defaults would apply)", Runtime: runtime}, nil
	}
	org := gw.OrganizationPolicy
	return companyPolicy{
		State: companyPolicyConfigured,
		Configured: fmt.Sprintf("configured in %s — pii_action %s, daily cost %.2f / monthly %.2f per use case, %d forbidden tool/action pattern(s), %s",
			path, org.Defaults.PIIAction, org.Defaults.DailyCost, org.Defaults.MonthlyCost, len(org.Constraints.ForbiddenTools), companyApprovalSummary(org.Constraints.ActionApprovals)),
		Runtime: runtime,
	}, nil
}

// gatewayConfigActivation states whether a running gateway of this
// installation reports having loaded the gateway config with this digest.
func gatewayConfigActivation(cfg *config.Config, digest string) string {
	v := runtimestatus.NewReader().Assess(cfg.DataDir, runtimestatus.Fingerprint(cfg.SigningKey), nil, time.Now())
	l := runtimestatus.ProveGatewayConfig(v, v.Err == "", digest)
	if l.State == runtimestatus.LoadedMatchesFile {
		return "ACTIVE — a running gateway reports this exact file as loaded"
	}
	return "NOT PROVEN ACTIVE (" + l.State + ": " + l.Reason + "). The company policy is loaded when 'talon serve' starts; a change to it needs a restart"
}

// fleetActivation states what the runtime records alone say about whether a
// running process will serve the newly registered use case. It is the
// registration output's fallback when the effective report is unavailable.
func fleetActivation(cfg *config.Config) string {
	v := runtimestatus.NewReader().Assess(cfg.DataDir, runtimestatus.Fingerprint(cfg.SigningKey), nil, time.Now())
	if v.Err != "" {
		return "this installation's runtime records could not be read (" + v.Err + "), so whether a running Talon process serves this use case is not known."
	}
	if !anyRunning(&v) {
		return "no Talon process of this installation is running. `talon serve` loads this use case when it starts."
	}
	// What the running processes report about re-reading agent files
	// (#575): a rejected re-scan blocks every activation until it is fixed.
	f := runtimestatus.ReloadFactsOf(v, "")
	switch {
	case len(f.RejectedCauses) > 0:
		return "a Talon process is running, but it rejected the last change to the fleet and keeps serving the previous one, so this use case is not active. Blocking: " + strings.Join(f.RejectedCauses, "; ") + ". Fix that; the next re-scan (" + f.Setting() + ") loads the current files."
	case f.Disabled:
		return "a Talon process is running, but it does not re-scan agents_dir (agents_reload_interval is \"0\"): it loads this use case only when it starts. Restart `talon serve`."
	}
	return "a Talon process is running and loads the use case at its next re-scan of agents_dir (" + f.Setting() + "); if that re-scan rejects the fleet, the previous one keeps serving and this use case is not active."
}

// validateAgentContent runs the strict loader and the effective action
// policy compiler with the company policy over the rendered bytes.
func validateAgentContent(ctx context.Context, content []byte) error {
	dir, err := os.MkdirTemp("", "talon-agents-add-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	p := filepath.Join(dir, agentcatalog.AgentConfigFilename)
	if err := os.WriteFile(p, content, 0o600); err != nil {
		return err
	}
	pol, err := policy.LoadPolicy(ctx, agentcatalog.AgentConfigFilename, false, dir) // the mode fleet discovery loads with
	if err != nil {
		return err
	}
	if err := policy.ValidateNoUnknownFields(p); err != nil {
		return err
	}
	offline, err := offlineServeContextFromGateway()
	if err != nil {
		return err
	}
	_, err = action.CompileEffectiveActionPolicy(pol, offline.Company)
	return err
}

// removeTempFile removes the temporary file of a publication. A variable so
// a test can make exactly that cleanup fail.
var removeTempFile = os.Remove

// publishAgentFile creates the agent file without overwriting. It reports
// three separate facts (#567 review):
//
//   - published: the identity of the file that is now at plan.Path, set as
//     soon as it was linked into place. From then on the file exists and the
//     caller owns it, whatever else fails;
//   - residual: a temporary file that could not be removed. That is a
//     leftover to report, not a failed publication;
//   - err: why the file was NOT published (published is nil then).
func publishAgentFile(plan *agentsAddPlan) (published os.FileInfo, residual string, err error) {
	if err := os.MkdirAll(plan.Dir, 0o755); err != nil {
		return nil, "", fmt.Errorf("creating %s: %w", plan.Dir, err)
	}
	tmp, err := os.CreateTemp(plan.Dir, ".agent.talon.yaml.*")
	if err != nil {
		return nil, "", fmt.Errorf("writing %s: %w", plan.Path, err)
	}
	tmpName := tmp.Name()
	discard := func(cause error) (os.FileInfo, string, error) {
		_ = tmp.Close()
		if rerr := removeTempFile(tmpName); rerr != nil && !errors.Is(rerr, os.ErrNotExist) {
			return nil, fmt.Sprintf("the temporary file %s could not be removed (%v); it is not an agent file and no process loads it", tmpName, rerr), cause
		}
		return nil, "", cause
	}
	if _, err := tmp.Write(plan.Content); err != nil {
		return discard(fmt.Errorf("writing %s: %w", plan.Path, err))
	}
	if err := tmp.Close(); err != nil {
		return discard(fmt.Errorf("writing %s: %w", plan.Path, err))
	}
	//nolint:gosec // G302: agent files hold no secret (key binding is a vault NAME) and must be readable by the serving process
	if err := os.Chmod(tmpName, 0o644); err != nil {
		return discard(err)
	}
	// The temporary name and the link are one file: its identity, taken
	// before the link, is what a rollback later compares before it removes
	// anything. Nothing after the link can lose it.
	identity, err := os.Lstat(tmpName)
	if err != nil {
		return discard(fmt.Errorf("writing %s: %w", plan.Path, err))
	}
	// os.Link refuses an existing target, so the file of the name is never
	// overwritten.
	if err := os.Link(tmpName, plan.Path); err != nil {
		return discard(fmt.Errorf("creating %s: %w", plan.Path, err))
	}
	published = identity
	if rerr := removeTempFile(tmpName); rerr != nil && !errors.Is(rerr, os.ErrNotExist) {
		residual = fmt.Sprintf("the temporary file %s could not be removed (%v); it is not an agent file and no process loads it", tmpName, rerr)
	}
	return published, residual, nil
}

// verifyFleetAfterAddFn is the post-write fleet check; a variable so a test
// can fail the registration after the agent file exists (the rollback path).
var verifyFleetAfterAddFn = verifyFleetAfterAdd

func verifyFleetAfterAdd(ctx context.Context, cfg *config.Config, plan *agentsAddPlan) error {
	scan, err := agentcatalog.DiscoverAgents(ctx, cfg.AgentsDir)
	if err != nil {
		return err
	}
	for i := range scan.Agents {
		if scan.Agents[i].Name == plan.Name {
			return nil
		}
	}
	return fmt.Errorf("use case %q not found by the fleet scan after writing %s", plan.Name, plan.Path)
}

// newAgentKey returns a fresh 192-bit Talon key.
func newAgentKey() (string, error) {
	b := make([]byte, 24)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("generating a key: %w", err)
	}
	return "talon_uc_" + hex.EncodeToString(b), nil
}

// companyApprovalSummary counts the company approval requirements.
func companyApprovalSummary(aa *gateway.ActionApprovalsConstraint) string {
	if aa == nil {
		return "0 approval rule(s)"
	}
	return fmt.Sprintf("%d approval rule(s)", len(aa.Rules))
}
